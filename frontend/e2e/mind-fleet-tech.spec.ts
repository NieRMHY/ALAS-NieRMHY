test('保存响应在实例切换后到达时，清理成功提交的旧草稿', async ({page, techInstances}) => {
  const instance = techInstances.alt, draftKey = `azurpilot.fleet-tech.${instance}`
  let release: (() => void) | undefined
  await page.routeWebSocket('**/api/v1/ws', socket => {
    const server = socket.connectToServer(), methods = new Map<string, string>()
    socket.onMessage(message => {const value = JSON.parse(String(message)); methods.set(value.id, value.method); server.send(message)})
    server.onMessage(message => {
      const value = JSON.parse(String(message))
      if (value.ok && methods.get(value.id) === 'fleetTech.patch') release = () => socket.send(message)
      else socket.send(message)
    })
  })
  await page.goto(`/#/i/${instance}/task/FleetTechnology`)
  await page.getByLabel('搜索舰名或编号').fill('杜威')
  await page.getByRole('button', {name: '记录编辑模式', exact: true}).click()
  await page.getByRole('button', {name: '满星 杜威 (4)', exact: true}).click()
  await expect.poll(() => !!release).toBe(true)
  await page.evaluate(name => {location.hash = `/i/${name}/task/FleetTechnology`}, techInstances.main)
  await expect(page.getByRole('heading', {name: '舰队科技列表', exact: true})).toBeVisible()
  expect(await page.evaluate(key => sessionStorage.getItem(key), draftKey)).not.toBeNull()
  release!()
  await expect.poll(() => page.evaluate(key => sessionStorage.getItem(key), draftKey)).toBeNull()
  await page.evaluate(name => {location.hash = `/i/${name}/task/FleetTechnology`}, instance)
  await expect(page.getByRole('button', {name: /^保存待提交修改/})).toHaveCount(0)
  await page.getByLabel('搜索舰名或编号').fill('杜威')
  if (await page.getByRole('button', {name: '记录编辑模式', exact: true}).getAttribute('aria-pressed') !== 'true') await page.getByRole('button', {name: '记录编辑模式', exact: true}).click()
  await expect(page.getByRole('button', {name: '满星 杜威 (4)', exact: true})).toHaveAttribute('aria-pressed', 'true')
})

