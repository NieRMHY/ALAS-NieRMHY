import {expect, test as base, type Page} from '@playwright/test'

const test = base.extend<{techInstances: {main: string; alt: string}}>({
  techInstances: async ({page}, use, info) => {
    // 每例使用新实例，累计科技历史不会受其他心智用例的保存行为影响。
    const suffix = `${info.testId.replace(/[^a-z0-9-]/gi, '').slice(-12)}-${info.retry}`
    const names = {main: `tech-main-${suffix}`, alt: `tech-alt-${suffix}`}
    await page.goto('/')
    for (const name of Object.values(names)) await rpc(page, 'instances.create', {name})
    await page.goto('about:blank')
    await use(names)
  },
})

async function rpc(page: Page, method: string, params: Record<string, unknown>) {
  return page.evaluate(({method, params}) => new Promise<any>((resolve, reject) => {
    const socket = new WebSocket(`ws://${location.host}/api/v1/ws`)
    const timer = setTimeout(() => {socket.close(); reject(new Error('模拟接口超时'))}, 20000)
    socket.onopen = () => socket.send(JSON.stringify({v: 1, type: 'request', id: 'fleet-test', method, params}))
    socket.onmessage = event => {const value = JSON.parse(String(event.data)); if (value.id === 'fleet-test') {clearTimeout(timer); socket.close(); value.ok ? resolve(value.result) : reject(new Error(value.error.message))}}
    socket.onerror = () => {clearTimeout(timer); reject(new Error('模拟连接失败'))}
  }), {method, params})
}

async function choose(page: Page, label: string, option: string) {
  await page.getByRole('combobox', {name: label, exact: true}).click()
  await page.getByRole('option', {name: option, exact: true}).click()
}

